-- Ensure buckets exist in storage.buckets
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES 
    (
        'field-service-videos', 
        'field-service-videos', 
        false, 
        125829120, -- 120 MB limit
        ARRAY['video/mp4', 'video/quicktime', 'video/webm', 'video/x-matroska']
    ),
    (
        'video-artifacts', 
        'video-artifacts', 
        false, 
        20971520,  -- 20 MB limit for keyframes
        ARRAY['image/jpeg', 'image/png', 'image/webp']
    )
ON CONFLICT (id) DO UPDATE SET 
    public = false,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

-- Storage RLS Policies: field-service-videos
-- Pattern: <user_id>/<video_id>/<original_filename>
CREATE POLICY "Users can upload their own videos"
    ON storage.objects FOR INSERT
    TO authenticated
    WITH CHECK (
        bucket_id = 'field-service-videos' AND
        (storage.foldername(name))[1] = auth.uid()::text
    );

